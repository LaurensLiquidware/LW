// writeNotices generates THIRD-PARTY-NOTICES.txt from what actually shipped.
//
// Section 4 of the Sparks Tool Project Review Checklist requires third-party
// license texts and attribution notices to be included with the tool. Generating
// the file rather than maintaining it by hand means it cannot drift from the
// dependency set: the npm texts come from the Angular builder's own attribution
// output for the packages it bundled, and the Go texts are read out of the
// resolved modules in the module cache.
func writeNotices(repo, webDir, exePath, noticesPath, goarch string) (int, error) {
	var b strings.Builder

	fmt.Fprintf(&b, "THIRD PARTY NOTICES\n")
	fmt.Fprintf(&b, "%s %s\n\n", version.ProductName, version.AppVersion)
	b.WriteString(wrapText(
		"This file lists the third-party components distributed inside this tool, with "+
			"their license terms. Per section 3 of the Liquidware Sparks Tool License, third "+
			"party terms apply in addition to, or in lieu of, that license for the components "+
			"named below.", 80))
	b.WriteString("\n\n")
	b.WriteString(wrapText(
		"This file is generated by the build from the components that were actually "+
			"linked and bundled, so it matches the shipped executable. Build-only tooling "+
			"(the Angular CLI, TypeScript, Tailwind, the Go compiler) is not listed: it is "+
			"not distributed.", 80))
	b.WriteString("\n\n")

	b.WriteString(strings.Repeat("=", 80) + "\n")
	b.WriteString("NOTICE ON PROPRIETARY COMPONENTS\n")
	b.WriteString(strings.Repeat("=", 80) + "\n\n")
	b.WriteString(wrapText(
		"The PrimeNG and PrimeUI packages below are proprietary software licensed by "+
			"PrimeTek Informatics under the PrimeUI Commercial License. They are not open "+
			"source. PrimeNG was MIT-licensed through version 17.x; version 18.0 and later "+
			"moved to the commercial license. Redistributing these packages so that third "+
			"parties can develop with them requires a separate OEM license from PrimeTek; "+
			"shipping them inside a compiled application, as here, does not.", 80))
	b.WriteString("\n\n")

	sections := 0

	// npm: the Angular builder writes the full license text of everything it bundled.
	npmNotices, err := os.ReadFile(filepath.Join(webDir, "dist", "3rdpartylicenses.txt"))
	if err != nil {
		return 0, fmt.Errorf("cannot read the bundled-license manifest: %w", err)
	}
	b.WriteString(strings.Repeat("=", 80) + "\n")
	b.WriteString("BUNDLED JAVASCRIPT COMPONENTS\n")
	b.WriteString(strings.Repeat("=", 80) + "\n")
	text := strings.TrimSpace(string(npmNotices))
	b.WriteString("\n" + text + "\n\n")
	sections += strings.Count(text, "\nPackage: ") + strings.Count(text, "Package: ")

	// Go: read each module's own LICENSE out of the module cache.
	mods, err := goModules(exePath)
	if err != nil {
		return 0, err
	}
	names := make([]string, 0, len(mods))
	for n := range mods {
		names = append(names, n)
	}
	sort.Strings(names)

	b.WriteString(strings.Repeat("=", 80) + "\n")
	b.WriteString("LINKED GO COMPONENTS\n")
	b.WriteString(strings.Repeat("=", 80) + "\n\n")
	for _, name := range names {
		ver := mods[name]
		b.WriteString(strings.Repeat("-", 80) + "\n")
		fmt.Fprintf(&b, "Module: %s\nVersion: %s\nLicense: %s\n\n", name, ver, goLicenses[name])
		licText, path := readModuleLicense(name, ver)
		if licText == "" {
			fmt.Fprintf(&b, "  [The module's license file could not be read from the local module cache\n")
			fmt.Fprintf(&b, "   during this build. The license is %s; obtain the full text from the\n", goLicenses[name])
			fmt.Fprintf(&b, "   module's distribution.]\n\n")
			continue
		}
		_ = path
		b.WriteString(strings.TrimSpace(licText) + "\n\n")
		sections++
	}

	// Microsoft's loader DLL is embedded by go-webview2. Its BSD-3-Clause terms
	// require the notice to accompany a binary redistribution.
	b.WriteString(strings.Repeat("=", 80) + "\n")
	b.WriteString("EMBEDDED MICROSOFT COMPONENT\n")
	b.WriteString(strings.Repeat("=", 80) + "\n\n")
	b.WriteString(strings.Repeat("-", 80) + "\n")
	if _, ver, _, ok := webView2Loader(mods, goarch); ok {
		fmt.Fprintf(&b, "Component: Microsoft Edge WebView2 Loader (WebView2Loader.dll)\nVersion: %s\n", ver)
	} else {
		b.WriteString("Component: Microsoft Edge WebView2 Loader (WebView2Loader.dll)\n")
	}
	b.WriteString("License: BSD-3-Clause\n\n")
	b.WriteString(wrapText(
		"This library is embedded in the executable by github.com/jchv/go-webview2 and "+
			"loaded from memory when it is not present on disk. It is part of the Microsoft "+
			"Edge WebView2 SDK.", 80))
	b.WriteString("\n\n")
	if lic := webView2LoaderLicense(mods, goarch); lic != "" {
		b.WriteString(strings.TrimSpace(lic) + "\n\n")
		sections++
	} else {
		b.WriteString("  [The WebView2 SDK license file could not be read from the local module\n")
		b.WriteString("   cache during this build. The license is BSD-3-Clause; obtain the full\n")
		b.WriteString("   text from the Microsoft Edge WebView2 SDK distribution.]\n\n")
	}

	// The self-hosted webfont is redistributed inside the executable.
	b.WriteString(strings.Repeat("=", 80) + "\n")
	b.WriteString("BUNDLED FONT\n")
	b.WriteString(strings.Repeat("=", 80) + "\n\n")
	b.WriteString(strings.Repeat("-", 80) + "\n")
	b.WriteString("Component: Inter (variable, roman)\nLicense: SIL Open Font License 1.1 (OFL-1.1)\n")
	b.WriteString("Source: https://rsms.me/inter/\n\n")
	b.WriteString(wrapText(
		"Inter is supplied with the Liquidware design system and is embedded in this "+
			"executable so that no font is fetched from a network at runtime. It is licensed "+
			"under the SIL Open Font License, Version 1.1, which permits bundling and "+
			"redistribution with software. The full license text accompanies the font in the "+
			"design system distribution and is available from the source above.", 80))
	b.WriteString("\n")
	sections++

	if err := os.WriteFile(noticesPath, []byte(b.String()), 0o644); err != nil {
		return 0, err
	}
	return sections, nil
}

// moduleDir returns a module's directory inside the local module cache, or "" if
// it cannot be located.
func moduleDir(module, ver string) string {
	gomodcache := strings.TrimSpace(runCapture("go", "env", "GOMODCACHE"))
	if gomodcache == "" {
		return ""
	}
	// Module paths are case-encoded in the cache: an uppercase letter becomes "!x".
	var enc strings.Builder
	for _, r := range module {
		if r >= 'A' && r <= 'Z' {
			enc.WriteByte('!')
			enc.WriteRune(r + 32)
		} else {
			enc.WriteRune(r)
		}
	}
	dir := filepath.Join(gomodcache, enc.String()+"@"+ver)
	if fi, err := os.Stat(dir); err != nil || !fi.IsDir() {
		return ""
	}
	return dir
}

// readModuleLicense returns a module's license text and the path it was read
// from, both empty if no license file is present.
func readModuleLicense(module, ver string) (string, string) {
	dir := moduleDir(module, ver)
	if dir == "" {
		return "", ""
	}
	for _, name := range []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING"} {
		p := filepath.Join(dir, name)
		if b, err := os.ReadFile(p); err == nil {
			return string(b), p
		}
	}
	return "", ""
}

func runCapture(name string, args ...string) string {
	out, err := execCommandOutput(name, args...)
	if err != nil {
		return ""
	}
	return out
}

// wrapText hard-wraps to width columns for a plain-text notices file.
func wrapText(s string, width int) string {
	words := strings.Fields(s)
	var b strings.Builder
	col := 0
	for i, w := range words {
		if col > 0 && col+1+len(w) > width {
			b.WriteString("\n")
			col = 0
		} else if i > 0 && col > 0 {
			b.WriteString(" ")
			col++
		}
		b.WriteString(w)
		col += len(w)
	}
	return b.String()
}

// webView2LoaderLicense reads the WebView2 SDK's own LICENSE.txt from the
// module cache, so the shipped notice is the vendor's text rather than a
// paraphrase.
func webView2LoaderLicense(mods map[string]string, goarch string) string {
	p := webView2LoaderPath(mods, goarch)
	if p == "" {
		return ""
	}
	// .../webviewloader/sdk/<arch>/WebView2Loader.dll -> .../sdk/LICENSE.txt
	lic := filepath.Join(filepath.Dir(filepath.Dir(p)), "LICENSE.txt")
	b, err := os.ReadFile(lic)
	if err != nil {
		return ""
	}
	return string(b)
}
